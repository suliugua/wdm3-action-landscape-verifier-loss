BUDGET=200;WARMUP_MAX=50;WARMUP_MIN=5;PROBE_N=20;CK=20
BANDS=[(51,200),(201,500),(501,1000),(1000,99999)];SG='spatial'
ACCEPT_TYPES={'wu_a','probe_a','bb_a','bs_a'}

def _h(i):return hashlib.md5(','.join(str(x) for x in sorted(i)).encode()).hexdigest()[:12]
def _am(i,mz):
    for idx in i:
        c=flat_to_col(idx)
        for lo,hi in mz:
            if lo<=c<=hi:return True
    return False

def build_strata(anchor,diag):
    m=diag['mask'];v=diag.get('variant','conj_a');p=ANCHORS[anchor]['port']
    jd=os.path.join(PARENT_DIR,'wdm3_3d','results_3d','jac3d')
    jp=os.path.join(jd,f'jac_{anchor}_P{p}@1550nm_g0.npz')
    if not os.path.exists(jp):jp=os.path.join(jd,f'jac_{anchor}_P{p}@1550nm.npz')
    jac=load_jac_npz(jp);g=jac.get(f'gain_{v}',jac['gain_raw'])
    import config as _c;_c.PATCH_SIZES=PATCH_SIZES;_c.PATCH_TYPES=PATCH_TYPES
    ap=_global_patch_scan(np.abs(g),gain_raw=g)
    sc=[]
    for pp in ap:
        if _am(pp['indices'],m):continue
        gs=sum(abs(float(g[flat_to_col(i),flat_to_row(i)])) for i in pp['indices'] if 0<=flat_to_col(i)<N_COLS and 0<=flat_to_row(i)<N_ROWS)
        if gs<=0:continue
        sc.append({'hash':_h(pp['indices']),'indices':pp['indices'],'n':len(pp['indices']),'size':pp['size'],'score':gs})
    sc.sort(key=lambda x:x['score'],reverse=True)
    for i,s in enumerate(sc):s['rank']=i+1
    st={}
    for lo,hi in BANDS:st[f'band_{lo}_{hi}']=[s for s in sc if lo<=s.get('rank',0)<=hi]
    st[SG]=[];return st

def gen_spatial(n,cp,rng):
    qs=[(0,40,0,50),(40,80,0,50),(0,40,50,100),(40,80,50,100)]
    nq=max(1,n//4);seen=set();pts=[]
    for cl,ch,rl,rh in qs:
        cnt=0;att=0
        while cnt<nq and att<nq*30:
            att+=1;sz=int(rng.choice([3,4,5]))
            cm=max(cl,min(ch-sz,N_COLS-sz));rm=max(rl,min(rh-sz,N_ROWS-sz))
            if cm<=cl or rm<=rl:continue
            ci=int(rng.integers(cl,cm+1) if cm>cl else cl)
            ri=int(rng.integers(rl,rm+1) if rm>rl else rl)
            if ci+sz>N_COLS or ri+sz>N_ROWS:continue
            idxs=[];ov=False
            for di in range(sz):
                for dj in range(sz):
                    ix=(ci+di)*N_ROWS+(ri+dj)
                    if ix in cp:ov=True;break
                    idxs.append(ix)
                if ov:break
            if ov or not idxs:continue
            h=_h(idxs)
            if h in seen:continue
            seen.add(h);pts.append({'hash':h,'indices':sorted(idxs),'size':sz,'n':len(idxs),'score':float('nan')});cnt+=1
    return pts[:n]

def try_accept(s,idx,dg,ld,tr,z=2.0):
    n=len(idx);th=0.0  # SIGN GATE: flipped from compute_scaled_threshold (the ONLY protocol change)
    dF=s.try_patch(idx)
    ld.charge('candidate_reject',n=1);tr.eval_count=ld.eval_count
    if dF>th:
        if not ld.is_exhausted():
            s.commit_patch(idx);ld.charge('patch_accept',n=1);tr.eval_count=ld.eval_count;tr.cumulative_dJ+=dF;return dF,True,th
    return dF,False,th

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--anchor',required=True);parser.add_argument('--max-exec-eval',type=int,default=None);args=parser.parse_args()
    anchor=args.anchor;t0=time.time();rng=np.random.default_rng(RNG_BASE_SEED)
    arm_dir=os.path.join(RESULTS_BASE,'final_rerun_2026_08_13_protocol_v2',anchor,'sign_banded_unified',f'budget{BUDGET}','repeat0')
    os.makedirs(arm_dir,exist_ok=True);cp=os.path.join(arm_dir,'ckpt.json')
    print(f'SIGN-band variant of unified protocol: {anchor}')
    with open(os.path.join(RESULTS_BASE,'shared',anchor,'diagnosis.json')) as f:diag=json.load(f)
