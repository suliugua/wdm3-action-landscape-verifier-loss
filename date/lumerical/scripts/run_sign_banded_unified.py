    C=diag.get('C',0);mu=diag.get('mu_single',0)
    print(f'C={C:.2f} mu={mu:+.2e}')
    strata=build_strata(anchor,diag)
    port=ANCHORS[anchor]['port']
    jd=os.path.join(PARENT_DIR,'wdm3_3d','results_3d','jac3d')
    jp=os.path.join(jd,f'jac_{anchor}_P{port}@1550nm_g0.npz')
    if not os.path.exists(jp):jp=os.path.join(jd,f'jac_{anchor}_P{port}@1550nm.npz')
    import lum_backend,_lumopt_compat
    ledger=BudgetLedger(total_budget=BUDGET);traj=Trajectory('sign_banded_unified',anchor,BUDGET,0)
    committed=set();tested=set()
    if os.path.exists(cp):
        with open(cp) as f:ck=json.load(f)
        committed=set(ck['committed_pixels']);tested=set(ck['tested_hashes'])
        traj.steps=ck['trajectory_steps'];traj.cumulative_dJ=ck['trajectory_cumulative_dJ']
        traj.eval_count=ck['trajectory_eval_count'];ledger=BudgetLedger.from_dict(ck['ledger'])
        ec_resume = ck.get('eval_counter', 0)
        bi_resume = ck.get('band_idx', 0)
        print(f'[RESUME] eval={ec_resume}')
    else:
        # === Warmup + Probe in ONE Session ===
        with Session(anchor,tag='wu') as s:
            jac=load_jac_npz(jp);gn=jac['gain_raw'];pool=set();ac=0
            while not ledger.is_exhausted() and ac<WARMUP_MIN and ledger.eval_count<WARMUP_MAX:
                mk=apply_mask_to_field(gn.copy(),[])
                for idx in pool:mk[flat_to_col(idx),flat_to_row(idx)]=-float('inf')
                cs=get_top_k_indices(mk,DEFAULT_K)
                if not cs:break
                for idx in cs:
                    if ledger.is_exhausted() or ac>=WARMUP_MIN:break
                    if idx in pool:continue
                    dF,ok=s.try_single(idx,threshold=0.0);pool.add(idx)  # SIGN GATE
                    ledger.charge('candidate_accept' if ok else 'candidate_reject',n=1);traj.eval_count=ledger.eval_count
                    if ok:ac+=1;traj.cumulative_dJ+=dF;traj.record_step({'type':'wu_a','idx':idx,'dJ':dF})
                    else:traj.record_step({'type':'wu_r','idx':idx,'dJ':dF})
            committed={s['idx'] for s in traj.steps if s.get('type')=='wu_a'}
            for step in traj.steps:
                il=[step['idx']] if 'idx' in step else step.get('indices',[])
                if il:tested.add(_h(il))
            print(f'Warmup: {ledger.eval_count}e {len(committed)}a dJ={traj.cumulative_dJ:+.4e}')
            # Probe: 20 valid patch evals — STILL INSIDE Session
            keys=list(strata.keys());ki=0;cursor={k:0 for k in keys}
            apool={k:([c for c in strata[k] if c['hash'] not in tested] if k!=SG else None) for k in keys}
            pv=0
